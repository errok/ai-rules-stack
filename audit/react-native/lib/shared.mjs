const gitState = (dir) => {
  try {
    const sha = execSync('git rev-parse --short HEAD', { cwd: dir, encoding: 'utf8' }).trim();
    const dirty = execSync('git status --porcelain', { cwd: dir, encoding: 'utf8' }).trim() !== '';
    return `\`${sha}\`${dirty ? ' + uncommitted changes' : ''}`;
  } catch {
    return 'unknown';
  }
};

export const header = (title, command, ctx) => {
  const now = new Date().toISOString().slice(0, 16).replace('T', ' ');
  return [
    `# ${title}`,
    '',
    `> Generated by \`${command}\` on ${now} — do not edit by hand, re-run the command.`,
    `> Front ${gitState(FRONT_ROOT)} · back ${gitState(ctx.backDir)} (\`${relative(FRONT_ROOT, ctx.backDir)}\`)`,
    '',
  ].join('\n');
};

/** `[label](relative/path#L12)` to a front or back location, relative to the report folder. */
export const link = (ctx, loc, label) => {
  if (!loc) {
    return label ?? '?';
  }
  const abs = join(loc.repo === 'back' ? ctx.backDir : FRONT_ROOT, loc.file);
  const target = relative(OUT_DIR, abs).split(sep).join('/');
  return `[${label ?? `${loc.file}:${loc.line}`}](${target}#L${loc.line})`;
};

export const code = (text) => `\`${String(text).replace(/`/g, "'")}\``;

export const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');

export const writeReport = (fileName, content) => {
  mkdirSync(OUT_DIR, { recursive: true });
  const path = join(OUT_DIR, fileName);
  writeFileSync(path, `${content.trim()}\n`);
  return relative(FRONT_ROOT, path);
};
